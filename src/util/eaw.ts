// 零宽：零宽空格与方向控制、行 / 段分隔符、字连接符、变体选择符、BOM；另加组合字符（Mn、Me）。
const ZERO: ReadonlyArray<readonly [number, number]> = [
  [0x200b, 0x200f], [0x2028, 0x202e], [0x2060, 0x2064], [0xfe00, 0xfe0f], [0xfeff, 0xfeff], [0xe0100, 0xe01ef],
]
const COMBINING = /\p{Mn}|\p{Me}/u

function inRanges(cp: number, table: ReadonlyArray<readonly [number, number]>): boolean {
  let lo = 0
  let hi = table.length - 1
  while (lo <= hi) {
    const mid = (lo + hi) >> 1
    const [a, b] = table[mid]!
    if (cp < a) hi = mid - 1
    else if (cp > b) lo = mid + 1
    else return true
  }
  return false
}

function codepointWidth(cp: number): number {
  if (cp < 0x20 || (cp >= 0x7f && cp < 0xa0)) return 0
  if (inRanges(cp, ZERO) || COMBINING.test(String.fromCodePoint(cp))) return 0
  return inRanges(cp, WIDE) ? 2 : 1
}

const segmenter = new Intl.Segmenter('und', { granularity: 'grapheme' })

export function displayWidth(s: string): number {
  let w = 0
  for (const { segment } of segmenter.segment(s)) {
    let max = 0
    let emojiStyle = false
    for (const ch of segment) {
      const cp = ch.codePointAt(0)!
      if (cp === 0xfe0f) emojiStyle = true
      max = Math.max(max, codepointWidth(cp))
    }
    if (emojiStyle && /\p{Extended_Pictographic}/u.test(segment)) max = 2
    w += max
  }
  return w
}
